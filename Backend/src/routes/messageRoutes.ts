import { Router } from "express";
import { clearConversation, createGroup, getConversation, getGroupConversation, getGroupInfo, listConversations, markRead, searchMessages, sendMessage, setChatBackground, updateGroup } from "../controllers/messageController.js";
import { authenticate } from "../utils/authMiddleware.js";
const router = Router();
router.post("/send", authenticate, sendMessage);
router.get("/conversations", authenticate, listConversations);
router.post("/groups", authenticate, createGroup);
router.get("/groups/:conversationId/info", authenticate, getGroupInfo);
router.get("/groups/:conversationId", authenticate, getGroupConversation);
router.patch("/groups/:conversationId", authenticate, updateGroup);
router.get("/search", authenticate, searchMessages);
router.post("/:conversationId/read", authenticate, markRead);
router.delete("/:conversationId/clear", authenticate, clearConversation);
router.patch("/:conversationId/background", authenticate, setChatBackground);
router.get("/conversation/:userid", authenticate, getConversation);
export default router;